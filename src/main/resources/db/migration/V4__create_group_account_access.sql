CREATE TABLE group_account_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL
        REFERENCES budget_group(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL
        REFERENCES account(account_id) ON DELETE CASCADE,
    permission VARCHAR(10) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_group_account_access UNIQUE (group_id, account_id),
    CONSTRAINT ck_group_account_permission CHECK (
        permission IN ('READ', 'EDIT')
    )
);

CREATE INDEX idx_group_account_access_account
    ON group_account_access(account_id);