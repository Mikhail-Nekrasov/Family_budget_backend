CREATE TABLE group_invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL
        REFERENCES budget_group(id) ON DELETE CASCADE,
    invited_user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    invited_by_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_group_invitation UNIQUE (group_id, invited_user_id)
);

CREATE INDEX idx_group_invitation_recipient
    ON group_invitation(invited_user_id);