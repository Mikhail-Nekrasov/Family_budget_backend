CREATE TABLE budget_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_budget_group_name CHECK (BTRIM(name) <> '')
);

CREATE TABLE group_membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL
        REFERENCES budget_group(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    joined_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_group_membership UNIQUE (group_id, user_id)
);

CREATE INDEX idx_budget_group_owner ON budget_group(owner_id);

CREATE INDEX idx_group_membership_user ON group_membership(user_id);