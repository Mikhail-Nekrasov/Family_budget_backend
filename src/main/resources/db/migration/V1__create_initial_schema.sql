CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username)
);

CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uq_role_name UNIQUE (name)
);

CREATE TABLE users_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES role(id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    description VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    user_id BIGINT REFERENCES users(id),
    CONSTRAINT ck_category_type CHECK (type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    date_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(255),
    category_id BIGINT NOT NULL REFERENCES category(category_id),
    account_id BIGINT NOT NULL REFERENCES account(account_id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    CONSTRAINT ck_entry_type CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT ck_entry_amount CHECK (amount > 0)
);

CREATE TABLE transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account_id BIGINT NOT NULL REFERENCES account(account_id),
    to_account_id BIGINT NOT NULL REFERENCES account(account_id),
    amount NUMERIC(38, 2) NOT NULL,
    date_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(255),
    CONSTRAINT ck_transfer_amount CHECK (amount > 0),
    CONSTRAINT ck_transfer_accounts CHECK (from_account_id <> to_account_id)
);

CREATE INDEX idx_account_user ON account(user_id);
CREATE INDEX idx_category_user ON category(user_id);

CREATE INDEX idx_entry_user_date
    ON entry(user_id, date_time DESC, id DESC);

CREATE INDEX idx_entry_user_type_date
    ON entry(user_id, type, date_time DESC, id DESC);

CREATE INDEX idx_entry_account ON entry(account_id);
CREATE INDEX idx_entry_category ON entry(category_id);

CREATE INDEX idx_transfer_from_account ON transfer(from_account_id);
CREATE INDEX idx_transfer_to_account ON transfer(to_account_id);